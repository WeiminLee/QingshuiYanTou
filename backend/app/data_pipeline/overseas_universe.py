def universe_for(markets: list[str] | tuple[str, ...] | None = None) -> list[tuple[str, str, str, str]]:
    """返回 (symbol, name, industry, market) 列表。"""
    keys = list(markets) if markets else list(OVERSEAS_UNIVERSE)
    rows: list[tuple[str, str, str, str]] = []
    for market in keys:
        for symbol, name, industry in OVERSEAS_UNIVERSE.get(market, []):
            rows.append((symbol, name, industry, market))
    return rows
